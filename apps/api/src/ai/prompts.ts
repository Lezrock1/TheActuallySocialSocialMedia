  "distinct verifiable claims and check each one. If you have web search available, use " +
  "it thoroughly: search for each claim, consult several independent, reputable and " +
  "official sources (news agencies, official statements, primary documents, fact-checking " +
  "organisations), prefer the most recent reporting, and cross-check sources against each " +
  "other. Never rely on memory alone for recent events; the post date tells you how " +
  "current the information must be, and do not call a claim false only because it is " +
  "recent or beyond your knowledge. Format the reply as: a bold one-line verdict (True, " +
  "Mostly true, Misleading, False, or Unverified); then, for every claim that is wrong or " +
  "misleading, a bullet stating exactly what is wrong and what is correct, with concrete " +
  "facts (names, numbers, dates); then a final line listing the key sources used (outlet " +
  "names, and URLs if known). If everything is accurate, say so and name what confirms it. " +
  "If evidence is insufficient, say precisely what could not be verified. Be neutral, " +
  "independent of political affiliation, and keep it under 220 words.";

const EXPLAIN_SYSTEM_PROMPT =
  "You are a helpful assistant that explains social media posts, including " +
  "the main point and any essential technical terms or context. Start with a direct " +
  "one- or two-sentence explanation, then use at most 3 short bullets if useful. " +
  "Avoid repeating the post, long numbered sections, and unrelated background. Keep " +
  "the answer under 120 words, neutral.";

const CUSTOM_BASE_SYSTEM_PROMPT =
  "You are an assistant within a social media platform, helping a user understand " +
  "a specific post. You will receive the post context and the user's own instruction " +
  "or question. Answer directly and follow the user's requested format. Prefer a short " +
  "paragraph or a few concise Markdown bullets; avoid unnecessary sections and repetition. " +
  "Stay under 120 words unless the user explicitly requests more detail.";

export const FACTCHECK_SUMMARY_SYSTEM_PROMPT =
  "You will receive several independent fact-check results for the same social media post " +
  "from different users, potentially generated by different AI models. Start with exactly " +
  "one standalone line in this exact format: VERDICT: TRUE, VERDICT: UNCERTAIN, " +
  "VERDICT: FALSE, or VERDICT: PARTLY_FALSE. Choose TRUE only when the evidence " +
  "clearly supports the central claim; FALSE when it clearly contradicts it; PARTLY_FALSE " +
  "when the claim is materially misleading or only partly correct; and UNCERTAIN when " +
  "evidence is insufficient or the fact-checks disagree. After that line, summarize the " +
  "results in 1-3 concise, neutral sentences: where they agree and where they differ. " +
  "Do not repeat each result; capture only the essence. Reply in english.";

export function systemPromptForMode(mode: AiMode, language?: string, webContext?: string): string {
  const base = modePrompt(mode);
  return [
    base,
    language ? `Always write your entire reply in ${language}, regardless of the language of the post or of the sources.` : "",
    webContext ?? "",
  ].filter(Boolean).join("\n\n");
}

function modePrompt(mode: AiMode): string {
  switch (mode) {
    case "factcheck":
      return FACTCHECK_SYSTEM_PROMPT;
    case "explain":
      return EXPLAIN_SYSTEM_PROMPT;
    case "custom":
      return CUSTOM_BASE_SYSTEM_PROMPT;
  }
}

export interface PostContext {
  authorUsername: string;
  authorDisplayName: string | null;
  createdAt: Date;
  text: string | null;
  hasImage: boolean;
}

export function buildPostContextBlock(post: PostContext): string {
  const lines = [
    "Post context:",
    `Author: @${post.authorUsername}${post.authorDisplayName ? ` (${post.authorDisplayName})` : ""}`,
    `Posted at: ${post.createdAt.toISOString()}`,
    `Text: "${post.text ?? "(no text)"}"`,
  ];
  if (post.hasImage) {
    lines.push("Note: The post also contains an image (not visible to you).");
  }
  return lines.join("\n");
}

export function buildInitialUserMessage(
  mode: AiMode,
  post: PostContext,
  customPrompt?: string
): string {
  const context = buildPostContextBlock(post);
  if (mode === "custom") {
    return `${context}\n\nUser request: ${customPrompt}`;
  }
  return context;
}

export interface ExternalPostContext {
  platform: string;
  authorHandle: string;
  authorName?: string | null;
  text?: string | null;
  url: string;
  publishedAt?: string;
}

export function buildExternalContextBlock(external: ExternalPostContext): string {
  const lines = [
    "Post context:",
    `Source: ${external.platform} post – ${external.url}`,
    `Author: @${external.authorHandle}${external.authorName ? ` (${external.authorName})` : ""}`,
  ];
  if (external.publishedAt) lines.push(`Posted at: ${external.publishedAt}`);
  lines.push(`Text: "${external.text ?? "(no text)"}"`);
  return lines.join("\n");
}

export function buildExternalUserMessage(
  mode: AiMode,
  external: ExternalPostContext,
  customPrompt?: string
): string {
  const context = buildExternalContextBlock(external);
  if (mode === "custom") {
    return `${context}\n\nUser request: ${customPrompt}`;
  }
  return context;
}
